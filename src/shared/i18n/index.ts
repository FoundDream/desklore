const messages: Record<AppLocale, Record<MessageKey, string>> = {
  en: englishMessages,
  "zh-CN": simplifiedChineseMessages,
};

export function isAppLocale(value: unknown): value is AppLocale {
  return typeof value === "string" && appLocales.includes(value as AppLocale);
}

export function translate(
  locale: AppLocale,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[locale][key],
  );
}

export function outputLanguageName(locale: AppLocale): string {
  return locale === "zh-CN" ? "Simplified Chinese" : "English";
}
